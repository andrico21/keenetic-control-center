/// Errors produced while constructing localized pages.
#[derive(Debug)]
#[non_exhaustive]
pub enum SpikeError {
    /// A bundled Fluent resource was not UTF-8.
    InvalidUtf8,
    /// A bundled Fluent resource did not parse.
    InvalidFluent,
    /// A parsed Fluent resource could not be added to its bundle.
    FluentCollision,
    /// The expected Fluent message or its value was absent.
    MissingMessage,
    /// Fluent reported an error while formatting a message.
    FluentFormatting,
    /// Askama could not render the localized page.
    Template,
}

impl fmt::Display for SpikeError {
    #[inline]
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::InvalidUtf8 => "Fluent resource is not UTF-8",
            Self::InvalidFluent => "Fluent resource did not parse",
            Self::FluentCollision => "Fluent resource contains a duplicate message",
            Self::MissingMessage => "Fluent message is absent",
            Self::FluentFormatting => "Fluent message did not format",
            Self::Template => "Askama template did not render",
        })
    }
}

impl Error for SpikeError {}

/// A rendered page containing one localized greeting.
#[derive(askama::Template)]
#[template(
    source = "<!doctype html><html lang=\"{{ language }}\"><body><p>{{ greeting }}</p></body></html>",
    ext = "html"
)]
struct PageTemplate<'text> {
    /// The page language tag.
    language: &'text str,
    /// The localized greeting.
    greeting: &'text str,
}

/// Loads and formats one Fluent message from embedded bytes.
///
/// # Errors
///
/// Returns an error when the bytes, resource, message, or formatting are invalid.
fn fluent_message(locale: LanguageIdentifier, bytes: &'static [u8]) -> Result<String, SpikeError> {
    let source = str::from_utf8(bytes).map_err(|_error| SpikeError::InvalidUtf8)?;
    let resource = FluentResource::try_new(source.to_owned())
        .map_err(|(_resource, _errors)| SpikeError::InvalidFluent)?;
    let mut bundle = FluentBundle::new(Vec::from([locale]));
    bundle.set_use_isolating(false);
    bundle
        .add_resource(resource)
        .map_err(|_errors| SpikeError::FluentCollision)?;
    let message = bundle
        .get_message("greeting")
        .ok_or(SpikeError::MissingMessage)?;
    let pattern = message.value().ok_or(SpikeError::MissingMessage)?;
    let mut errors = Vec::new();
    let rendered = bundle
        .format_pattern(pattern, None, &mut errors)
        .into_owned();
    if errors.is_empty() {
        Ok(rendered)
    } else {
        Err(SpikeError::FluentFormatting)
    }
}

/// Renders the Russian greeting through Fluent and Askama.
///
/// # Errors
///
/// Returns an error when the embedded Fluent resource or template is invalid.
#[inline]
pub fn render_russian_page() -> Result<String, SpikeError> {
    render_page(
        "ru",
        langid!("ru"),
        include_bytes!("../locales/ru/main.ftl"),
    )
}

/// Renders the Kazakh greeting through Fluent and Askama.
///
/// # Errors
///
/// Returns an error when the embedded Fluent resource or template is invalid.
#[inline]
pub fn render_kazakh_page() -> Result<String, SpikeError> {
    render_page(
        "kk",
        langid!("kk"),
        include_bytes!("../locales/kk/main.ftl"),
    )
}

/// Renders one localized page.
///
/// # Errors
///
/// Returns an error when localization or template rendering fails.
fn render_page(
    language: &str,
    locale: LanguageIdentifier,
    bytes: &'static [u8],
) -> Result<String, SpikeError> {
    let greeting = fluent_message(locale, bytes)?;
    PageTemplate {
        language,
        greeting: &greeting,
    }
    .render()
    .map_err(|_error| SpikeError::Template)
}

/// MCP service generated by `rmcp` tool macros.
#[derive(Clone, Debug)]
#[non_exhaustive]
pub struct SpikeServer {
    /// Text prefixed to every tool response.
    prefix: String,
}

impl Default for SpikeServer {
    #[inline]
    fn default() -> Self {
        Self {
            prefix: String::from("spike:"),
        }
    }
}

/// Input accepted by the recording tool.
#[derive(Debug, serde::Deserialize, schemars::JsonSchema)]
struct RecordRequest {
    /// Label returned by the demonstration tool.
    label: String,
}

#[tool_router]
impl SpikeServer {
    /// Reports whether the spike service is ready.
    #[tool(
        description = "Report service readiness",
        annotations(read_only_hint = true)
    )]
    fn status(&self) -> String {
        format!("{}ready", self.prefix)
    }

    /// Records a supplied label in the demonstration response.
    #[tool(description = "Record a demonstration label")]
    fn record(&self, Parameters(RecordRequest { label }): Parameters<RecordRequest>) -> String {
        format!("{}{label}", self.prefix)
    }
}

#[tool_handler]
#[expect(
    clippy::unused_async_trait_impl,
    reason = "async is generated by the rmcp ServerHandler tool dispatch macro"
)]
impl ServerHandler for SpikeServer {
    #[inline]
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
    }
}

/// Constructs the Axum router containing the event stream route.
#[inline]
pub fn sse_router() -> Router {
    Router::new().route("/events", get(sse_events))
}

/// Streams one readiness event over server-sent events.
async fn sse_events() -> Sse<impl Stream<Item = Result<Event, Infallible>>> {
    Sse::new(stream::once(future::ready(Ok(Event::default()
        .event("status")
        .data("ready")))))
}

#[cfg(test)]
#[expect(
    clippy::missing_errors_doc,
    clippy::missing_panics_doc,
    reason = "test code is not rendered API documentation"
)]
#[expect(clippy::panic_in_result_fn, reason = "a test fails by panicking")]
mod tests {
    use rmcp::ServerHandler as _;

    use super::{SpikeServer, render_kazakh_page, render_russian_page, sse_router};

    /// Proves Russian and Kazakh Cyrillic messages pass through Fluent and Askama.
    #[test]
    fn renders_both_cyrillic_locales() -> Result<(), super::SpikeError> {
        let russian = render_russian_page()?;
        let kazakh = render_kazakh_page()?;
        assert!(
            russian.contains(
                "\u{41f}\u{440}\u{438}\u{432}\u{435}\u{442} \u{438}\u{437} Keenetic Control Center"
            ),
            "Russian Fluent message was not rendered"
        );
        assert!(
            kazakh.contains("Keenetic \u{431}\u{430}\u{441}\u{49b}\u{430}\u{440}\u{443} \u{43e}\u{440}\u{442}\u{430}\u{43b}\u{44b}\u{493}\u{44b}\u{43d}\u{430}\u{43d} \u{441}\u{4d9}\u{43b}\u{435}\u{43c}"),
            "Kazakh Fluent message was not rendered"
        );
        Ok(())
    }

    /// Proves the macro service advertises tools and the SSE route builds.
    #[test]
    fn constructs_macro_service_and_sse_route() {
        let server = SpikeServer::default();
        let info = server.get_info();
        assert!(
            info.capabilities.tools.is_some(),
            "rmcp service did not advertise tools"
        );
        drop(sse_router());
    }
}
