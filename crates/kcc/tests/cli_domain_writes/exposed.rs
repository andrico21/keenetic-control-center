/// One registry write operation and the CLI subcommand that runs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub(crate) struct Exposure {
    /// The curated domain.
    pub domain: DomainId,
    /// The registry operation name.
    pub op: &'static str,
    /// The subcommand words after `kcc`, e.g. `dhcp pool`.
    pub command: &'static str,
}

/// An [`Exposure`] row.
const fn on(domain: DomainId, op: &'static str, command: &'static str) -> Exposure {
    Exposure {
        domain,
        op,
        command,
    }
}

