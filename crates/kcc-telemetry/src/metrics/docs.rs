//! The metric catalogue as Markdown (`docs/METRICS.md`, written by
//! `cargo xtask gen-metric-docs`).

use core::fmt::Write as _;

use super::catalogue::{FAMILIES, Presence};

/// Introduction of the generated document.
const INTRO: &str = "# Metrics

Generated by `cargo xtask gen-metric-docs` from `crates/kcc-telemetry/src/metrics/catalogue.rs`;
do not edit by hand.

`kcc serve` exports these families on the rmcp-server-kit `/metrics` listener when
`[metrics] enabled = true` (default `127.0.0.1:9090`). The listener is plaintext and
unauthenticated by design, so it stays on loopback unless `allow_non_loopback = true`;
ports below 1024 are refused.

- A scrape renders the shared poller's cache and never calls a router. The exporter adds a
  permanent metrics subscription to that poller: light items every `interval` (default
  30 s, minimum 15 s), heavy items every `heavy_interval` (default 120 s, minimum 60 s).
  `show ip nat` and `show processes` are never polled.
- Data older than 3 of its intervals is omitted and `keenetic_up` becomes 0.
- Every router family carries `router`, the profile id.
- Per-client families exist only with `per_client = true`, for at most `per_client_max`
  clients per router (lowest MAC first; the number of the rest at the latest
  scrape is the gauge `kcc_metrics_series_dropped`). Clients are labelled with a `client-<16 hex>` pseudonym
  (a keyed hash of the MAC and the router, stable only while one kcc process runs)
  unless `per_client_label` is `name` or `mac`.
- The rmcp-server-kit families (`rmcp_server_kit_*`) are listed in the kit documentation.

| Name | Type | Labels | Present | Help |
|------|------|--------|---------|------|
";

/// Renders the catalogue table.
#[inline]
#[must_use]
pub fn markdown() -> String {
    let mut text = String::from(INTRO);
    for family in FAMILIES {
        let labels = if family.labels.is_empty() {
            "-".to_owned()
        } else {
            family
                .labels
                .iter()
                .map(|label| format!("`{label}`"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let presence = match family.presence {
            Presence::Always => "always",
            Presence::WhenReported => "when reported",
            Presence::PerClient => "`per_client = true`",
            Presence::SelfMetric => "self-metric",
        };
        let _infallible = writeln!(
            text,
            "| `{}` | {} | {labels} | {presence} | {} |",
            family.name,
            family.kind.as_str(),
            family.help
        );
    }
    text
}
