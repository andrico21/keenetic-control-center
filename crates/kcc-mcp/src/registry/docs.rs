//! `docs/MCP_TOOLS.md`, rendered from the tool registry (`cargo xtask gen-tool-docs`).

use core::fmt::Write as _;

use super::definitions::{ToolDescription, tools};

/// Toolsets in documentation order.
const TOOLSETS: &[(&str, &str)] = &[
    (
        "core",
        "Registered by default: fleet, catalog, jobs, configuration state and the main reads.",
    ),
    (
        "network-write",
        "Network reads and writes: interfaces, WAN, Wi-Fi, mesh, clients, DHCP, segments, routing, policies, NAT, firewall.",
    ),
    ("vpn", "VPN clients and servers."),
    ("dns", "DNS proxy and KeenDNS."),
    (
        "system-admin",
        "System changes, diagnostics, router users, services, components, storage, schedules, logging and backups.",
    ),
    ("migration", "Configuration migration between routers."),
    (
        "presets",
        "Settings presets: capture settings groups from a router or backup and apply them to another router.",
    ),
    ("raw", "Catalog-validated raw RCI and CLI access."),
];

/// Renders the complete tool reference as Markdown.
#[inline]
#[must_use]
pub fn markdown() -> String {
    let all = tools();
    let mut text = String::from(
        "# MCP tools\n\n\
         Generated by `cargo xtask gen-tool-docs` from the `kcc-mcp` tool registry; do not edit.\n\n\
         Every router-targeting tool takes `host` (a router profile id). Handlers re-check the\n\
         exact operation permission and router scope; the permission column is the coarse gate\n\
         the RBAC layer applies to the tool. Destructive operations need `confirm: true` and\n\
         `[mcp] allow_destructive = true`. No tool saves implicitly.\n",
    );
    for &(toolset, summary) in TOOLSETS {
        let members = all
            .iter()
            .filter(|tool| tool.toolset == toolset)
            .collect::<Vec<_>>();
        let _ignored = write!(
            text,
            "\n## Toolset `{toolset}` ({} tools)\n\n{summary}\n\n\
             | Tool | Permission | Read-only | Destructive | Operations | Description |\n\
             |---|---|---|---|---|---|\n",
            members.len()
        );
        for tool in members {
            row(&mut text, tool);
        }
    }
    let _ignored = write!(text, "\nTotal: {} tools.\n", all.len());
    text
}

/// Appends one table row.
fn row(text: &mut String, tool: &ToolDescription) {
    let permission = serde_json::to_value(tool.permission)
        .ok()
        .and_then(|value| value.as_str().map(str::to_owned))
        .unwrap_or_default();
    let ops = if tool.ops.is_empty() {
        "-".to_owned()
    } else {
        tool.ops
            .iter()
            .map(|op| format!("`{op}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ignored = writeln!(
        text,
        "| `{}` | {permission} | {} | {} | {ops} | {} |",
        tool.name,
        yes(tool.read_only),
        yes(tool.destructive),
        tool.description
    );
}

/// Renders a flag.
const fn yes(flag: bool) -> &'static str {
    if flag { "yes" } else { "no" }
}
