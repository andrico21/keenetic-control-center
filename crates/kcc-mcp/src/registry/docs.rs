//! `docs/MCP_TOOLS.md`, rendered from the tool registry (`cargo xtask gen-tool-docs`).

use core::fmt::Write as _;

use super::definitions::{ToolDescription, tools};

/// Toolsets in documentation order.
const TOOLSETS: &[(&str, &str)] = &[
    (
        "core",
        "Registered by default: fleet, catalog, jobs, configuration state and the main reads.",
    ),
    (
        "network-write",
        "Network reads and writes: interfaces, WAN, Wi-Fi, mesh, clients, DHCP, segments, routing, policies, NAT, firewall.",
    ),
    ("vpn", "VPN clients and servers."),
    ("dns", "DNS proxy and KeenDNS."),
    (
        "system-admin",
        "System changes, diagnostics, router users, services, components, storage, schedules, logging and backups.",
    ),
    ("migration", "Configuration migration between routers."),
    (
        "presets",
        "Settings presets: capture settings groups from a router or backup and apply them to another router.",
    ),
    ("raw", "Catalog-validated raw RCI and CLI access."),
];

/// Renders the complete tool reference as Markdown.
#[inline]
#[must_use]
pub fn markdown() -> String {
    let all = tools();
    let mut text = String::from(
        "# MCP tools\n\n\
         Generated by `cargo xtask gen-tool-docs` from the `kcc-mcp` tool registry; do not edit.\n\n\
         Every router-targeting tool takes `host` (a router profile id). Handlers re-check the\n\
         exact operation permission and router scope; the permission column is the coarse gate\n\
         the RBAC layer applies to the tool. Destructive operations need `confirm: true` and\n\
         `[mcp] allow_destructive = true`; a refusal says which one is missing with the error\n\
         code `destructive_disabled` or `confirm_required` (also used when a management,\n\
         migration, or preset change lacks `confirm: true`). A write the router accepts but\n\
         does not apply fails with\n\
         `verification_failed` and the `field` that read back unchanged; `validation_failed`\n\
         means the input was refused before anything was sent. No tool saves implicitly.\n\n\
         Every mutating raw tool, including `kcc_cli_parse`, requires confirmation and the server\n\
         switch for management or destructive requests, and the `Destructive` role permission for\n\
         destructive ones. The recovery timer kcc arms around a management change is authorized\n\
         by the change's own permission.\n\
         Negative `no` commands are destructive. Management nodes retain their recovery timer\n\
          even when a destructive sibling raises the maximum request risk.\n\n\
         A management change on a router whose recovery mechanism cannot be determined (it\n\
         reports neither a system mode kcc knows nor a fail-safe timer) fails with\n\
         `router_mode_unknown` before anything is sent.\n\n\
          After recovery arms, unsuccessful cleanup returns `management_applied_fail_safe_armed`\n\
           when at least one change item succeeded, or `management_outcome_unknown_fail_safe_armed`\n\
           when every change was refused, work failed, or its outcome is unknown. Successful reads\n\
           do not count as applied changes. Batch recovery errors retain `responses`, including\n\
           the refused `ok: false` items; partial application refers only to successful changes.\n\
           When the arm is refused and so is its disarm, the code is\n\
           `management_not_sent_fail_safe_armed`: nothing else was sent, but the timer may be armed.\n\
           When the configuration was saved but the disarm failed, the code is\n\
           `management_saved_fail_safe_armed`: the router may restart with its saved configuration,\n\
           which includes the change.\n\
           These codes carry a localized English `message` explaining recovery;\n\
           the timer remains armed and will restore the saved configuration, discarding unsaved changes.\n\
           A locally refused migration commit returns `management_not_committed_fail_safe_armed`:\n\
           nothing was sent, the timer remains armed, and the migration is retained for retry.\n\
           A migration rollback the router accepted before it stopped answering returns\n\
           `migration_rollback_restarting`: the router is restarting with its saved configuration\n\
           and the migration is closed, so a retry cannot reboot it again.\n\
           Successful cleanup preserves the original work error; when the arm itself was refused\n\
           and its disarm accepted, that error also carries a `message` saying nothing was applied\n\
           and the timer is off. Failed-change audit parameters\n\
          include `fail_safe_armed: true` when recovery remains armed.\n",
    );
    for &(toolset, summary) in TOOLSETS {
        let members = all
            .iter()
            .filter(|tool| tool.toolset == toolset)
            .collect::<Vec<_>>();
        let _ignored = write!(
            text,
            "\n## Toolset `{toolset}` ({} tools)\n\n{summary}\n\n\
             | Tool | Permission | Read-only | Destructive | Operations | Description |\n\
             |---|---|---|---|---|---|\n",
            members.len()
        );
        for tool in members {
            row(&mut text, tool);
        }
    }
    let _ignored = write!(text, "\nTotal: {} tools.\n", all.len());
    text
}

/// Appends one table row.
fn row(text: &mut String, tool: &ToolDescription) {
    let permission = serde_json::to_value(tool.permission)
        .ok()
        .and_then(|value| value.as_str().map(str::to_owned))
        .unwrap_or_default();
    let ops = if tool.ops.is_empty() {
        "-".to_owned()
    } else {
        tool.ops
            .iter()
            .map(|op| format!("`{op}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ignored = writeln!(
        text,
        "| `{}` | {permission} | {} | {} | {ops} | {} |",
        tool.name,
        yes(tool.read_only),
        yes(tool.destructive),
        tool.description
    );
}

/// Renders a flag.
const fn yes(flag: bool) -> &'static str {
    if flag { "yes" } else { "no" }
}
