//! The RMCP server handler: tool dispatch, router snapshot and catalog resources, prompts.

use kcc_app::{permissions::Permission, registry::authorize};
use kcc_i18n::{bundle::tr, locale::Locale};
use rmcp::{
    ErrorData, ServerHandler,
    model::{
        GetPromptRequestParams, GetPromptResponse, GetPromptResult, ListPromptsResult,
        ListResourcesResult, ListToolsResult, PaginatedRequestParams, Prompt, PromptMessage,
        ReadResourceRequestParams, ReadResourceResponse, ReadResourceResult, Resource,
        ResourceContents, Role as McpRole, ServerCapabilities, ServerConfig,
    },
    service::{RequestContext, RoleServer},
    tool_handler,
};
use rmcp_server_kit::rbac::current_identity;
use serde_json::json;

use crate::{
    KccMcp, McpFailure,
    generic::rci::catalog_for_version,
    prompts::PROMPTS,
    support::{
        errors::{failure_error, internal_error},
        shape::shape,
        validate::{MAX_PATH_CHARS, valid_host, valid_text},
    },
};

#[tool_handler(router = self.tool_router.clone())]
#[expect(
    clippy::unused_async_trait_impl,
    reason = "async is generated by the rmcp ServerHandler tool dispatch macro"
)]
impl ServerHandler for KccMcp {
    #[inline]
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(
            ServerCapabilities::builder()
                .enable_tools()
                .enable_resources()
                .enable_prompts()
                .build(),
        )
    }

    async fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, ErrorData> {
        Ok(ListToolsResult::with_all_items(
            self.visible_tools(current_identity().is_some()),
        ))
    }

    async fn list_resources(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListResourcesResult, ErrorData> {
        let identity = self.identity().map_err(failure_error)?;
        let resources = self
            .registry
            .list()
            .map_err(|error| internal_error("resources/list", &error))?
            .into_iter()
            .filter(|entry| authorize(&identity.role, Permission::Read, &entry.profile.id).is_ok())
            .map(|entry| {
                Resource::new(
                    format!("kcc://router/{}/snapshot", entry.profile.id),
                    format!("{} snapshot", entry.profile.id),
                )
                .with_mime_type("application/json")
            })
            .collect();
        Ok(ListResourcesResult::with_all_items(resources))
    }

    async fn read_resource(
        &self,
        request: ReadResourceRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<ReadResourceResponse, ErrorData> {
        let identity = self.identity().map_err(failure_error)?;
        let uri = request.uri;
        if let Some(host) = uri
            .strip_prefix("kcc://router/")
            .and_then(|rest| rest.strip_suffix("/snapshot"))
        {
            valid_host(host).map_err(failure_error)?;
            authorize(&identity.role, Permission::Read, host)
                .map_err(|_error| failure_error(McpFailure::Forbidden))?;
            let mut receiver = self.poller.subscribe(host).await;
            if receiver.borrow().is_none() {
                receiver
                    .changed()
                    .await
                    .map_err(|error| internal_error("resources/read", &error))?;
            }
            let result = receiver
                .borrow()
                .clone()
                .ok_or_else(|| failure_error(McpFailure::RouterUnreachable))?
                .map_err(|error| internal_error("resources/read", &error))?;
            let value = json!({
                "host": host,
                "system": result.system,
                "internet": result.internet,
                "interfaces": result.interfaces_summary,
                "clients_count": result.clients_count,
                "wifi": result.wifi_summary,
                "last_change": result.last_change,
                "fetched_at": result.fetched_at
            });
            let text = shape(self, value, None).map_err(failure_error)?;
            return Ok(ReadResourceResult::new(vec![
                ResourceContents::text(text, uri).with_mime_type("application/json"),
            ])
            .into());
        }
        if let Some(rest) = uri.strip_prefix("kcc://catalog/") {
            let (version, path) = rest
                .split_once('/')
                .ok_or_else(|| failure_error(McpFailure::InvalidArguments))?;
            let catalog = catalog_for_version(version).map_err(failure_error)?;
            let decoded = path.replace("%20", " ");
            valid_text(&decoded, MAX_PATH_CHARS).map_err(failure_error)?;
            let command = catalog
                .lookup(&decoded)
                .ok_or_else(|| failure_error(McpFailure::InvalidArguments))?;
            let value = json!({
                "version": version,
                "path": command.path,
                "kind": format!("{:?}", command.kind).to_ascii_lowercase(),
                "prefix_no": command.prefix_no,
                "schema": catalog.to_json_schema(&decoded)
            });
            let text = shape(self, value, None).map_err(failure_error)?;
            return Ok(ReadResourceResult::new(vec![
                ResourceContents::text(text, uri).with_mime_type("application/json"),
            ])
            .into());
        }
        Err(failure_error(McpFailure::InvalidArguments))
    }

    async fn list_prompts(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListPromptsResult, ErrorData> {
        Ok(ListPromptsResult::with_all_items(
            PROMPTS
                .iter()
                .map(|&(name, description, _key)| Prompt::new(name, Some(description), None))
                .collect(),
        ))
    }

    async fn get_prompt(
        &self,
        request: GetPromptRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<GetPromptResponse, ErrorData> {
        let &(_name, _description, key) = PROMPTS
            .iter()
            .find(|&&(name, _description, _key)| name == request.name)
            .ok_or_else(|| failure_error(McpFailure::InvalidArguments))?;
        Ok(GetPromptResult::new(vec![PromptMessage::new_text(
            McpRole::User,
            tr(Locale::En, key, None),
        )])
        .into())
    }
}
