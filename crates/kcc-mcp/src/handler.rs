//! The RMCP server handler: tool dispatch, router snapshot and catalog resources, prompts;
//! every request runs as its caller, a kcc account token's account resolved at its start.

use alloc::sync::Arc;

use kcc_i18n::{bundle::tr, locale::Locale};
use rmcp::{
    ErrorData, ServerHandler,
    handler::server::tool::ToolCallContext,
    model::{
        CallToolRequestParams, CallToolResponse, GetPromptRequestParams, GetPromptResponse,
        GetPromptResult, ListPromptsResult, ListResourcesResult, ListToolsResult,
        PaginatedRequestParams, Prompt, PromptMessage, ReadResourceRequestParams,
        ReadResourceResponse, Role as McpRole, ServerCapabilities, ServerConfig,
    },
    service::{RequestContext, RoleServer},
    tool_handler,
};
use rmcp_server_kit::rbac::current_identity;

use crate::{
    KccMcp, McpFailure,
    prompts::PROMPTS,
    support::{errors::failure_error, gates, principal},
};

#[tool_handler(router = self.tool_router.clone())]
#[expect(
    clippy::unused_async_trait_impl,
    reason = "async is generated by the rmcp ServerHandler tool dispatch macro"
)]
impl ServerHandler for KccMcp {
    #[inline]
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(
            ServerCapabilities::builder()
                .enable_tools()
                .enable_resources()
                .enable_prompts()
                .build(),
        )
    }

    #[inline]
    // NOT cancel-safe: it runs the called tool, which may change the router or local state and
    // queue an audit entry before the future is dropped.
    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResponse, ErrorData> {
        let method = principal::of_request(&context);
        principal::scoped(self.principals.clone(), method, async move {
            self.record_key_use().await;
            let gates = Arc::new(self.gates_now());
            if !self.admits(&gates, &request.name) {
                return Err(ErrorData::invalid_params("tool not found", None));
            }
            if principal::is_kcc_account() {
                let identity = self.identity().map_err(failure_error)?;
                if !self.permits(&identity.role, &request.name) {
                    return Err(failure_error(McpFailure::Forbidden));
                }
            }
            gates::scoped(
                gates,
                self.tool_router
                    .call(ToolCallContext::new(self, request, context)),
            )
            .await
        })
        .await
    }

    #[inline]
    // cancel-safe: the account resolution only reads.
    async fn list_tools(
        &self,
        _request: Option<PaginatedRequestParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<ListToolsResult, ErrorData> {
        let method = principal::of_request(&context);
        principal::scoped(self.principals.clone(), method, async {
            self.listed_tools(current_identity().is_some())
                .map(ListToolsResult::with_all_items)
                .map_err(failure_error)
        })
        .await
    }

    #[inline]
    // cancel-safe: the account resolution only reads.
    async fn list_resources(
        &self,
        _request: Option<PaginatedRequestParams>,
        context: RequestContext<RoleServer>,
    ) -> Result<ListResourcesResult, ErrorData> {
        let method = principal::of_request(&context);
        principal::scoped(self.principals.clone(), method, async {
            self.resources_list()
        })
        .await
    }

    #[inline]
    // NOT cancel-safe: a refused read queues an audit entry that may be written after the future is
    // dropped; the snapshot wait itself only reads.
    async fn read_resource(
        &self,
        request: ReadResourceRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<ReadResourceResponse, ErrorData> {
        let method = principal::of_request(&context);
        principal::scoped(self.principals.clone(), method, self.resource_read(request)).await
    }

    #[inline]
    // cancel-safe: it has no await point.
    async fn list_prompts(
        &self,
        _request: Option<PaginatedRequestParams>,
        _context: RequestContext<RoleServer>,
    ) -> Result<ListPromptsResult, ErrorData> {
        Ok(ListPromptsResult::with_all_items(
            PROMPTS
                .iter()
                .map(|&(name, description, _key)| Prompt::new(name, Some(description), None))
                .collect(),
        ))
    }

    #[inline]
    // cancel-safe: it has no await point.
    async fn get_prompt(
        &self,
        request: GetPromptRequestParams,
        _context: RequestContext<RoleServer>,
    ) -> Result<GetPromptResponse, ErrorData> {
        let &(_name, _description, key) = PROMPTS
            .iter()
            .find(|&&(name, _description, _key)| name == request.name)
            .ok_or_else(|| failure_error(McpFailure::InvalidArguments))?;
        Ok(GetPromptResult::new(vec![PromptMessage::new_text(
            McpRole::User,
            tr(Locale::En, key, None),
        )])
        .into())
    }
}
