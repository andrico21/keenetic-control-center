//! MCP API-key creation and hash-only persistence.

use core::fmt;

use rmcp_server_kit::auth::{ApiKeyEntry, generate_api_key};
use secrecy::{ExposeSecret as _, SecretString};
use serde::{Deserialize, Serialize};

use crate::{
    permissions::{
        Role,
        assignment::{GrantError, RoleGrant},
    },
    persist::{Migration, StateDoc, StateError, StateStore},
};

/// A persisted API-key record. It contains only the Argon2id hash, never the
/// plaintext token, and redacts the hash from `Debug` output.
#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[non_exhaustive]
pub struct StoredApiKey {
    /// Human-readable key name and MCP principal identity.
    pub name: String,
    /// Argon2id PHC hash generated by rmcp-server-kit.
    pub hash: String,
    /// Granted role name.
    pub role: String,
    /// Creation time as Unix seconds.
    pub created_at: u64,
    /// Most recent successful use as Unix seconds.
    pub last_used_at: Option<u64>,
}

impl fmt::Debug for StoredApiKey {
    #[inline]
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let Self {
            name,
            hash: _,
            role,
            created_at,
            last_used_at,
        } = self;
        f.debug_struct("StoredApiKey")
            .field("name", name)
            .field("hash", &"<redacted>")
            .field("role", role)
            .field("created_at", created_at)
            .field("last_used_at", last_used_at)
            .finish()
    }
}

/// API keys persisted in `api_keys.json`.
#[derive(Debug, Default, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[non_exhaustive]
#[expect(
    clippy::module_name_repetitions,
    reason = "the stored document name distinguishes it from one API key record"
)]
pub struct ApiKeysDocument {
    /// Hash-only key records.
    pub keys: Vec<StoredApiKey>,
}

impl StateDoc for ApiKeysDocument {
    const FILE_NAME: &'static str = "api_keys.json";
    const SCHEMA: u32 = 1;
    const MIGRATIONS: &'static [Migration] = &[];
}

/// A newly created key. The plaintext is returned once in a redacting secret
/// wrapper and is never serializable or persisted by this module.
#[derive(Debug)]
#[non_exhaustive]
pub struct CreatedApiKey {
    /// Plaintext bearer token to show once to the operator.
    pub plaintext: SecretString,
    /// Persisted metadata, containing the hash but not plaintext.
    pub record: StoredApiKey,
}

/// API-key service errors.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum ApiKeyError {
    /// State storage failed.
    #[error(transparent)]
    State(#[from] StateError),
    /// rmcp-server-kit could not generate or hash the key.
    #[error("API key generation failed")]
    Generation,
    /// A key with the same principal name already exists.
    #[error("API key name already exists")]
    DuplicateName,
    /// The role cannot be granted by the acting role.
    #[error(transparent)]
    Grant(#[from] GrantError),
}

/// Creates a new API key holding `role`, granted by `actor`.
///
/// Only the hash and metadata are persisted. `role` must exist and `actor` must dominate
/// it ([`Role::dominates`]); the roles lock is held until the key is stored.
///
/// # Errors
///
/// Returns [`ApiKeyError::Grant`] for an unknown or undominated role, a generic
/// generation error, a duplicate-name error, or a state storage error. No error
/// contains plaintext key material.
#[inline]
pub fn create_api_key(
    store: &StateStore,
    actor: &Role,
    name: String,
    role: String,
    created_at: u64,
) -> Result<CreatedApiKey, ApiKeyError> {
    let _grant = RoleGrant::by(store, actor, &role)?;
    let (plaintext, hash) = generate_api_key().map_err(|_error| ApiKeyError::Generation)?;
    let record = StoredApiKey {
        name,
        hash,
        role,
        created_at,
        last_used_at: None,
    };
    store.update(|document: &mut ApiKeysDocument| {
        if document.keys.iter().any(|key| key.name == record.name) {
            return Err(ApiKeyError::DuplicateName);
        }
        document.keys.push(record.clone());
        Ok(())
    })??;
    Ok(CreatedApiKey {
        plaintext: SecretString::from(plaintext),
        record,
    })
}

/// Loads the persisted records in rmcp-server-kit's authentication shape.
///
/// # Errors
///
/// Returns a state error if `api_keys.json` cannot be read.
#[inline]
pub fn api_key_entries(store: &StateStore) -> Result<Vec<ApiKeyEntry>, StateError> {
    let document = store.read::<ApiKeysDocument>()?.unwrap_or_default();
    Ok(document
        .keys
        .into_iter()
        .map(|key| ApiKeyEntry::new(key.name, key.hash, key.role))
        .collect())
}

/// Updates the last-used timestamp under the existing state-file lock.
///
/// # Errors
///
/// Returns a state error if the record cannot be read or written.
#[inline]
pub fn record_api_key_use(
    store: &StateStore,
    name: &str,
    used_at: u64,
) -> Result<bool, StateError> {
    store.update(|document: &mut ApiKeysDocument| {
        let Some(key) = document.keys.iter_mut().find(|key| key.name == name) else {
            return false;
        };
        key.last_used_at = Some(used_at);
        true
    })
}

/// Returns the plaintext token for immediate presentation without allowing an
/// accidental formatting conversion through this API.
#[inline]
#[must_use]
pub fn expose_created_key(created: &CreatedApiKey) -> &str {
    created.plaintext.expose_secret()
}
