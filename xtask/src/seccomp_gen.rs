//! `seccomp gen`: unions the traces with the container-runtime exec prologue and writes
//! `deploy/podman/seccomp-kcc.json`, grouped by the fixed group map and sorted.

use alloc::collections::BTreeSet;
use std::{fs, io, path::Path};

use serde::Serialize;

use crate::{
    Verdict,
    failure::GateError,
    seccomp::{default_trace_dir, read_traces},
    seccomp_groups::{
        CLONE_NAMESPACE_FLAGS, CLONE_RATIONALE, CLONE3_RATIONALE, ENOSYS, EQUIVALENTS, GROUPS,
        PROLOGUE, PROLOGUE_RATIONALE,
    },
};

/// The generated profile, relative to the repository root.
const PROFILE: &str = "deploy/podman/seccomp-kcc.json";

/// The profile's leading comment.
const COMMENT: &str = "Syscall allowlist for the kcc container, generated by `cargo xtask seccomp gen` from traces taken by `cargo xtask seccomp trace`. Do not edit by hand: assign new syscalls a group in xtask/src/seccomp_groups.rs. Derivation and verification: deploy/podman/README.md";

/// The whole profile, in output key order.
#[derive(Debug, Serialize)]
struct Profile {
    /// Leading comment.
    #[serde(rename = "_comment")]
    comment: &'static str,
    /// Refuse everything not listed.
    #[serde(rename = "defaultAction")]
    default_action: &'static str,
    /// `EPERM`.
    #[serde(rename = "defaultErrnoRet")]
    default_errno: u32,
    /// Filtered ABIs.
    architectures: [&'static str; 5],
    /// The rules.
    syscalls: Vec<Rule>,
}

/// One rule of the profile.
#[derive(Debug, Serialize)]
struct Rule {
    /// Rationale.
    #[serde(rename = "_group")]
    group: &'static str,
    /// Syscall names, sorted.
    names: Vec<String>,
    /// `SCMP_ACT_ALLOW` or `SCMP_ACT_ERRNO`.
    action: &'static str,
    /// Argument filter (only `clone`).
    #[serde(skip_serializing_if = "Vec::is_empty")]
    args: Vec<Arg>,
    /// Errno of an `SCMP_ACT_ERRNO` rule.
    #[serde(rename = "errnoRet", skip_serializing_if = "Option::is_none")]
    errno: Option<u32>,
}

/// One argument comparison.
#[derive(Debug, Serialize)]
struct Arg {
    /// Argument index.
    index: u32,
    /// Mask.
    value: u64,
    /// Expected masked value.
    #[serde(rename = "valueTwo")]
    value_two: u64,
    /// Comparison.
    op: &'static str,
}

/// Builds the profile JSON from `traced`.
///
/// # Errors
///
/// The sorted names no group maps.
fn render(traced: &BTreeSet<String>) -> Result<String, Vec<String>> {
    let mut wanted: BTreeSet<&str> = traced.iter().map(String::as_str).collect();
    wanted.extend(PROLOGUE);
    for (legacy, modern) in EQUIVALENTS {
        if wanted.contains(legacy) {
            wanted.extend(modern.iter());
        }
    }
    let wants_clone = wanted.remove("clone");
    let _clone3_always_errno: bool = wanted.remove("clone3");
    let mut rules = Vec::new();
    for &(rationale, members) in GROUPS {
        let names: Vec<String> = members
            .iter()
            .filter(|name| wanted.remove(**name))
            .map(|name| (*name).to_owned())
            .collect();
        rules.push(allow(rationale, names));
    }
    let prologue: Vec<String> = PROLOGUE
        .iter()
        .filter(|name| wanted.remove(**name))
        .map(|name| (*name).to_owned())
        .collect();
    rules.push(allow(PROLOGUE_RATIONALE, prologue));
    if !wanted.is_empty() {
        return Err(wanted.into_iter().map(str::to_owned).collect());
    }
    rules.retain(|rule| !rule.names.is_empty());
    for rule in &mut rules {
        rule.names.sort_unstable();
    }
    if wants_clone {
        let mut clone = allow(CLONE_RATIONALE, vec!["clone".to_owned()]);
        clone.args.push(Arg {
            index: 0,
            value: CLONE_NAMESPACE_FLAGS,
            value_two: 0,
            op: "SCMP_CMP_MASKED_EQ",
        });
        rules.push(clone);
    }
    rules.push(Rule {
        group: CLONE3_RATIONALE,
        names: vec!["clone3".to_owned()],
        action: "SCMP_ACT_ERRNO",
        args: Vec::new(),
        errno: Some(ENOSYS),
    });
    let profile = Profile {
        comment: COMMENT,
        default_action: "SCMP_ACT_ERRNO",
        default_errno: 1,
        architectures: [
            "SCMP_ARCH_X86_64",
            "SCMP_ARCH_X86",
            "SCMP_ARCH_X32",
            "SCMP_ARCH_AARCH64",
            "SCMP_ARCH_ARM",
        ],
        syscalls: rules,
    };
    serde_json::to_string_pretty(&profile)
        .map(|mut text| {
            text.push('\n');
            text
        })
        .map_err(|error| vec![format!("<serialization failed: {error}>")])
}

/// An `SCMP_ACT_ALLOW` rule.
const fn allow(group: &'static str, names: Vec<String>) -> Rule {
    Rule {
        group,
        names,
        action: "SCMP_ACT_ALLOW",
        args: Vec::new(),
        errno: None,
    }
}

/// Writes the profile from the traces in `dir`, or with `check` compares it to the
/// committed one.
///
/// # Errors
///
/// [`GateError::Read`] for unreadable traces or profile, [`GateError::Write`] when the
/// profile cannot be written.
pub(crate) fn generate<W>(
    root: &Path,
    dir: Option<&Path>,
    check: bool,
    out: &mut W,
) -> Result<Verdict, GateError>
where
    W: io::Write,
{
    let dir_path = dir.map_or_else(|| default_trace_dir(root), Path::to_path_buf);
    let traced = read_traces(&dir_path)?;
    let text = match render(&traced) {
        Ok(text) => text,
        Err(unmapped) => {
            writeln!(
                out,
                "seccomp gen: unmapped syscalls (assign each a group in xtask/src/seccomp_groups.rs): {}",
                unmapped.join(", ")
            )?;
            return Ok(Verdict::Fail);
        }
    };
    let path = root.join(PROFILE);
    if check {
        let committed = fs::read_to_string(&path).map_err(|source| GateError::Read {
            path: path.clone(),
            source,
        })?;
        if committed == text {
            writeln!(out, "seccomp gen --check: {PROFILE} is byte-identical")?;
            return Ok(Verdict::Pass);
        }
        report_difference(&committed, &text, out)?;
        return Ok(Verdict::Fail);
    }
    fs::write(&path, &text).map_err(|source| GateError::Write {
        path: path.clone(),
        detail: source.to_string(),
    })?;
    writeln!(out, "seccomp gen: wrote {PROFILE} from {}", dir_path.display())?;
    Ok(Verdict::Pass)
}

/// Prints the syscall names only one side allows.
///
/// # Errors
///
/// Report write failures.
fn report_difference<W>(committed: &str, fresh: &str, out: &mut W) -> Result<(), GateError>
where
    W: io::Write,
{
    let names = |text: &str| -> BTreeSet<String> {
        let value = serde_json::from_str::<serde_json::Value>(text).unwrap_or_default();
        value
            .get("syscalls")
            .and_then(serde_json::Value::as_array)
            .cloned()
            .unwrap_or_default()
            .iter()
            .filter_map(|rule| rule.get("names")?.as_array().cloned())
            .flatten()
            .filter_map(|name| name.as_str().map(str::to_owned))
            .collect()
    };
    let (old, new) = (names(committed), names(fresh));
    let added: Vec<&str> = new.difference(&old).map(String::as_str).collect();
    let removed: Vec<&str> = old.difference(&new).map(String::as_str).collect();
    writeln!(
        out,
        "seccomp gen --check: {PROFILE} differs; added [{}], removed [{}] (review, then run `cargo xtask seccomp gen`)",
        added.join(", "),
        removed.join(", ")
    )?;
    Ok(())
}

#[cfg(test)]
#[expect(
    clippy::missing_panics_doc,
    reason = "test code is not rendered API documentation"
)]
mod tests {
    use alloc::collections::BTreeSet;

    use super::render;
    use crate::seccomp_groups::{GROUPS, PROLOGUE};

    #[test]
    fn every_name_belongs_to_one_group() {
        let mut seen = BTreeSet::new();
        for name in GROUPS.iter().flat_map(|&(_, members)| members.iter()) {
            assert!(seen.insert(*name), "{name} is in two groups");
        }
        assert!(!seen.contains("clone") && !seen.contains("clone3"), "clone rules are fixed");
        assert!(PROLOGUE.iter().all(|name| *name != "clone"), "no clone in the prologue");
    }

    #[test]
    fn an_unmapped_syscall_fails_and_a_mapped_one_renders_sorted() {
        let unmapped: BTreeSet<String> = ["read", "kexec_load"].map(str::to_owned).into();
        assert_eq!(render(&unmapped), Err(vec!["kexec_load".to_owned()]));
        let traced: BTreeSet<String> = ["write", "read", "getsockopt", "clone", "open"]
            .map(str::to_owned)
            .into();
        let text = render(&traced).unwrap_or_default();
        let profile: serde_json::Value = serde_json::from_str(&text).unwrap_or_default();
        let rules = profile.get("syscalls").and_then(serde_json::Value::as_array);
        let names: Vec<&str> = rules
            .into_iter()
            .flatten()
            .filter_map(|rule| rule.get("names").and_then(serde_json::Value::as_array))
            .flatten()
            .filter_map(serde_json::Value::as_str)
            .collect();
        for expected in ["getsockopt", "openat", "clone", "clone3", "execve"] {
            assert!(names.contains(&expected), "{expected} missing from {names:?}");
        }
        assert_eq!(render(&traced).ok(), Some(text), "rendering is deterministic");
    }
}
